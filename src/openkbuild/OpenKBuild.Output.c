#include <stdbool.h>
#include <stdio.h>

#include "openkbuild/OpenKBuild.Config.h"
#include "openkbuild/OpenKBuild.Options.h"
#include "openkbuild/OpenKBuild.Output.h"

/** The forms a string takes in the three outputs. */
typedef enum StringForm
{
        kStringC,
        kStringMake,
        kStringToml,
} tStringForm;

/**
 * @brief Writes a string as a quoted literal.
 *
 * The strings hold no control characters (OpenKBuild_Options_ReadValue() refuses them), so only
 * the quote and the backslash need an escape in C and TOML; make also needs $ doubled and #
 * escaped, as both start something in a makefile.
 *
 * @param[in,out] aInOut_pFile The stream.
 * @param[in]     aIn_pText    The string.
 * @param[in]     aForm        Where the literal goes.
 */
static void
WriteString(FILE* aInOut_pFile, const char* aIn_pText, tStringForm aForm)
{
        fputc('"', aInOut_pFile);
        for(const char* pCharacter = aIn_pText; *pCharacter != '\0'; pCharacter++)
        {
                char character = *pCharacter;

                if(character == '"' || character == '\\')
                        fputc('\\', aInOut_pFile);
                else if(aForm == kStringMake && character == '$')
                        fputc('$', aInOut_pFile);
                else if(aForm == kStringMake && character == '#')
                        fputc('\\', aInOut_pFile);
                fputc(character, aInOut_pFile);
        }
        fputc('"', aInOut_pFile);
}

/**
 * @brief Writes the first line of a generated file.
 *
 * @param[in]     aIn_pConfig  The configuration, for the names of its files.
 * @param[in,out] aInOut_pFile The stream.
 * @param[in]     aIn_pStart   The start of a comment: the C opening or "#".
 * @param[in]     aIn_pEnd     The end of a comment: the C closing or "".
 */
static void
WriteBanner(const OpenKBuild_tConfig* aIn_pConfig,
            FILE*                     aInOut_pFile,
            const char*               aIn_pStart,
            const char*               aIn_pEnd)
{
        fprintf(aInOut_pFile,
                "%s Generated by openkbuild from %s and %s; do not edit.%s\n",
                aIn_pStart,
                aIn_pConfig->pOptions->pPath,
                aIn_pConfig->pPath,
                aIn_pEnd);
}

/**
 * @brief Writes config.h: a CONFIG_NAME macro for each option that is set.
 *
 * A bool or tristate y is 1, a tristate m defines CONFIG_NAME_MODULE as 1 instead, an int is its
 * number and a string a C string literal. An option that is not set has no macro.
 *
 * @param[in]     aIn_pConfig   The resolved configuration.
 * @param[in,out] aInOut_pFile  The stream.
 * @return false when writing fails.
 */
bool
OpenKBuild_Output_WriteHeader(const OpenKBuild_tConfig* aIn_pConfig, FILE* aInOut_pFile)
{
        const OpenKBuild_tOptions* pOptions = aIn_pConfig->pOptions;

        WriteBanner(aIn_pConfig, aInOut_pFile, "/*", " */");
        fputs("#pragma once\n", aInOut_pFile);
        for(size_t index = 0; index < pOptions->count; index++)
        {
                const OpenKBuild_tOption* pOption = &pOptions->pItems[ index ];
                const OpenKBuild_tValue*  pValue  = &aIn_pConfig->pValues[ index ];

                if(!aIn_pConfig->pIsSet[ index ])
                        continue;
                switch(pOption->type)
                {
                case OpenKBuild_kBool:
                case OpenKBuild_kTristate:
                        fprintf(aInOut_pFile,
                                "#define CONFIG_%s%s 1\n",
                                pOption->pName,
                                pValue->state == OpenKBuild_kModule ? "_MODULE" : "");
                        break;
                case OpenKBuild_kInt:
                        fprintf(aInOut_pFile,
                                "#define CONFIG_%s %lld\n",
                                pOption->pName,
                                (long long) pValue->number);
                        break;
                case OpenKBuild_kString:
                        fprintf(aInOut_pFile, "#define CONFIG_%s ", pOption->pName);
                        WriteString(aInOut_pFile, pValue->pText, kStringC);
                        fputc('\n', aInOut_pFile);
                        break;
                }
        }
        return (ferror(aInOut_pFile) == 0);
}

/**
 * @brief Writes config.mk: a CONFIG_NAME variable for BSD Make for each option that is set.
 *
 * A bool or tristate is y or m, an int its number and a string its C string literal, with $ and #
 * escaped for make. A makefile adds sources with SRCS-${CONFIG_NAME}+= file.c and builds SRCS-y.
 *
 * @param[in]     aIn_pConfig   The resolved configuration.
 * @param[in,out] aInOut_pFile  The stream.
 * @return false when writing fails.
 */
bool
OpenKBuild_Output_WriteMake(const OpenKBuild_tConfig* aIn_pConfig, FILE* aInOut_pFile)
{
        const OpenKBuild_tOptions* pOptions = aIn_pConfig->pOptions;

        WriteBanner(aIn_pConfig, aInOut_pFile, "#", "");
        for(size_t index = 0; index < pOptions->count; index++)
        {
                const OpenKBuild_tOption* pOption = &pOptions->pItems[ index ];
                const OpenKBuild_tValue*  pValue  = &aIn_pConfig->pValues[ index ];

                if(!aIn_pConfig->pIsSet[ index ])
                        continue;
                fprintf(aInOut_pFile, "CONFIG_%s=\t", pOption->pName);
                switch(pOption->type)
                {
                case OpenKBuild_kBool:
                case OpenKBuild_kTristate:
                        fputs(pValue->state == OpenKBuild_kModule ? "m" : "y", aInOut_pFile);
                        break;
                case OpenKBuild_kInt:
                        fprintf(aInOut_pFile, "%lld", (long long) pValue->number);
                        break;
                case OpenKBuild_kString:
                        WriteString(aInOut_pFile, pValue->pText, kStringMake);
                        break;
                }
                fputc('\n', aInOut_pFile);
        }
        return (ferror(aInOut_pFile) == 0);
}

/**
 * @brief Writes a configuration that sets every option to its default, with its help above it.
 *
 * @param[in]     aIn_pOptions  The options.
 * @param[in,out] aInOut_pFile  The stream.
 * @return false when writing fails.
 */
bool
OpenKBuild_Output_WriteDefaults(const OpenKBuild_tOptions* aIn_pOptions, FILE* aInOut_pFile)
{
        static const char* const kStates[] = {
                [OpenKBuild_kNo]     = "\"n\"",
                [OpenKBuild_kModule] = "\"m\"",
                [OpenKBuild_kYes]    = "\"y\"",
        };

        fprintf(aInOut_pFile,
                "# The defaults of %s, written by openkbuild defconfig.\n",
                aIn_pOptions->pPath);
        for(size_t index = 0; index < aIn_pOptions->count; index++)
        {
                const OpenKBuild_tOption* pOption = &aIn_pOptions->pItems[ index ];
                const OpenKBuild_tValue*  pValue  = &pOption->defaultValue;

                fputc('\n', aInOut_pFile);
                if(pOption->pHelp != NULL)
                {
                        /* One comment line for each line of the help. */
                        fputs("# ", aInOut_pFile);
                        for(const char* pCharacter = pOption->pHelp; *pCharacter != '\0';
                            pCharacter++)
                        {
                                if(*pCharacter == '\n' && pCharacter[ 1 ] != '\0')
                                        fputs("\n# ", aInOut_pFile);
                                else if(*pCharacter != '\n')
                                        fputc(*pCharacter, aInOut_pFile);
                        }
                        fputc('\n', aInOut_pFile);
                }
                fprintf(aInOut_pFile, "%s = ", pOption->pName);
                switch(pOption->type)
                {
                case OpenKBuild_kBool:
                        fputs(pValue->state == OpenKBuild_kYes ? "true" : "false", aInOut_pFile);
                        break;
                case OpenKBuild_kTristate:
                        fputs(kStates[ pValue->state ], aInOut_pFile);
                        break;
                case OpenKBuild_kInt:
                        fprintf(aInOut_pFile, "%lld", (long long) pValue->number);
                        break;
                case OpenKBuild_kString:
                        WriteString(aInOut_pFile, pValue->pText, kStringToml);
                        break;
                }
                fputc('\n', aInOut_pFile);
        }
        return (ferror(aInOut_pFile) == 0);
}
